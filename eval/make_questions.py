"""Draft eval/questions.csv. Run once; then the owner reviews every row and fills `verified`.

Answerable questions are generated by an LLM from ONE specific section's text (never from
memory), and expected_sections is set by this script from the section it used, not by the LLM.
not_in_docs and follow_up rows are written by hand below.

Usage: python eval/make_questions.py [--force]
"""

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import chunk  # noqa: E402
import providers  # noqa: E402

OUT = ROOT / "eval" / "questions.csv"
COLUMNS = ["question", "prior_question", "expected_sections", "reference_answer", "type", "verified"]

# Chosen by hand to cover different topics; plain headings like "Effectivity" are skipped.
LAW_ONLY = [2, 3, 4, 7, 10, 11, 13, 14, 19, 21, 30, 35, 39, 43, 47]
IRR_ONLY = [2, 31, 44, 45, 47, 55, 56, 57, 58, 59, 60, 61]
BOTH = [(5, 7), (6, 8), (9, 12), (12, 22), (15, 17), (16, 18), (17, 28), (18, 30),
        (23, 26), (24, 9), (26, 32), (28, 34), (37, 36)]

# Flagged for the owner to confirm they really are absent from RA 9262 and its IRR.
NOT_IN_DOCS = [
    "What is the penalty for estafa?",
    "What are the grounds for annulment of marriage?",
    "What is the penalty for cyber libel?",
    "How many days of maternity leave does a female employee get?",
    "How do I register a business name in the Philippines?",
    "What is the minimum wage in Metro Manila?",
    "Can a foreigner own land in the Philippines?",
]

# (prior question, follow-up, expected labels). The last one is a known retrieval miss.
FOLLOW_UPS = [
    ("What is a Barangay Protection Order?", "How long does it last?", ["RA 9262, Section 14"]),
    ("Is stalking a crime under RA 9262?", "What is the penalty for it?", ["RA 9262, Section 6"]),
    ("What is a temporary protection order?", "How long is it effective?", ["RA 9262, Section 15"]),
    ("Who may file a petition for a protection order?", "Where do they file it?", ["RA 9262, Section 10"]),
    ("What is a Barangay Protection Order?", "Can my ex-boyfriend be covered by this?", ["RA 9262, Section 3"]),
]

PROMPT = """Below is one section of a Philippine law or its implementing rules.
Write ONE question that an ordinary person might ask and that this section answers, and a
reference answer of one to three sentences that uses only facts stated in this section.
Rules: do not mention section numbers in the question; do not use outside knowledge;
{extra}
Return JSON: {{"question": "...", "reference_answer": "..."}}

{label}
{text}"""

FOLLOW_UP_PROMPT = """A user asked "{prior}" and then asked the follow-up "{question}".
Using only the section text below, write a reference answer of one to three sentences to the
follow-up. Use only facts stated in the text. If the text does not settle the question, say what
it does state. Return JSON: {{"reference_answer": "..."}}

{label}
{text}"""


def sections() -> dict[str, dict]:
    out = {}
    for document in ("law", "irr"):
        for s in chunk.load_sections(document):
            out[chunk.citation(document, s)] = s
    return out


def section_text(s: dict) -> str:
    return (s["heading"] or "") + "\n" + "\n".join(s["lines"])


def ask(prompt: str) -> dict:
    messages = [{"role": "user", "content": prompt}]
    response = providers.client().chat.completions.create(
        model=providers.JUDGE_MODEL, messages=messages, temperature=0,
        response_format={"type": "json_object"})
    return json.loads(response.choices[0].message.content)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true", help="overwrite a reviewed questions.csv")
    args = parser.parse_args()
    if OUT.exists() and not args.force:
        sys.exit("eval/questions.csv exists and may contain review edits. Use --force to overwrite.")

    secs = sections()
    law = lambda n: f"RA 9262, Section {n}"
    irr = lambda n: next(c for c in secs if c.startswith("IRR,") and c.endswith(f"Section {n}"))
    rows = []

    def generate(label, expected, kind, extra=""):
        g = ask(PROMPT.format(label=label, text=section_text(secs[label]), extra=extra))
        rows.append({"question": g["question"], "prior_question": "", "expected_sections": "; ".join(expected),
                     "reference_answer": g["reference_answer"], "type": kind, "verified": ""})
        print(f"{kind:12} {'; '.join(expected):45} {g['question']}")

    for n in LAW_ONLY:
        generate(law(n), [law(n)], "law_only")
    for n in IRR_ONLY:
        generate(irr(n), [irr(n)], "irr_only",
                 extra="ask about a detail that is specific to these implementing rules;")
    for law_n, irr_n in BOTH:
        generate(law(law_n), [law(law_n), irr(irr_n)], "both")
    for q in NOT_IN_DOCS:
        rows.append({"question": q, "prior_question": "", "expected_sections": "",
                     "reference_answer": "Refuse: not covered by RA 9262 or its IRR.",
                     "type": "not_in_docs", "verified": ""})
    for prior, q, expected in FOLLOW_UPS:
        text = "\n\n".join(f"{e}\n{section_text(secs[e])}" for e in expected)
        g = ask(FOLLOW_UP_PROMPT.format(prior=prior, question=q, label="", text=text))
        rows.append({"question": q, "prior_question": prior, "expected_sections": "; ".join(expected),
                     "reference_answer": g["reference_answer"], "type": "follow_up", "verified": ""})
        print(f"{'follow_up':12} {'; '.join(expected):45} {prior} -> {q}")

    with OUT.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {len(rows)} rows to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
